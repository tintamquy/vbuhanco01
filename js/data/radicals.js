// Helper functions
export function getRadicalById(id) {
  return radicals214.find(radical => radical.id === id);
}

export function getRadicalByChar(char) {
  return radicals214.find(radical => radical.radical === char);
}

export function getRadicalsByStrokes(strokeCount) {
  return radicals214.filter(radical => radical.strokes === strokeCount);
}

export function getRadicalsByPosition(position) {
  return radicals214.filter(radical => radical.position.includes(position));
}

// Group radicals by stroke count
export function getRadicalsByStrokeGroups() {
  const groups = {};
  radicals214.forEach(radical => {
    if (!groups[radical.strokes]) {
      groups[radical.strokes] = [];
    }
    groups[radical.strokes].push(radical);
  });
  return groups;
}

